features = ['Home_Avg_Scored', 'Home_Avg_Conceded', 'Away_Avg_Scored', 'Away_Avg_Conceded']
X = df[features]
y = df['TotalGoals']

kf = KFold(n_splits=5, shuffle=True, random_state=42)

models = {
    'Linear Regression': LinearRegression(),
    'Decision Tree': DecisionTreeRegressor(max_depth=5, min_samples_split=20, random_state=42),
    'Random Forest': RandomForestRegressor(n_estimators=100, max_depth=6, min_samples_split=20, random_state=42),
    'Gradient Boosting': GradientBoostingRegressor(n_estimators=100, max_depth=3, learning_rate=0.05, random_state=42),
    'KNN Regressor (Bonus)': KNeighborsRegressor(n_neighbors=25)
}

results = []
predictions = {}

for name, model in models.items():
    preds = cross_val_predict(model, X, y, cv=kf)
    predictions[name] = preds
    mse = mean_squared_error(y, preds)
    rmse = np.sqrt(mse)
    mae = mean_absolute_error(y, preds)
    r2 = r2_score(y, preds)
    residuals = y - preds
    std_res = np.std(residuals, ddof=1)

    results.append({
        'Model Architecture': name,
        'MSE': mse,
        'RMSE': rmse,
        'MAE': mae,
        'R^2 Score': r2,
        'Residual Std': std_res
    })

comparison_df = pd.DataFrame(results)
print("--- Model Performance Comparison Table ---")
display(comparison_df.round(4))

