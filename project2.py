import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import KFold, cross_val_predict
from sklearn.metrics import (precision_score, recall_score, f1_score,
                             fbeta_score, matthews_corrcoef, roc_curve, roc_auc_score)

try:
    df = pd.read_csv('results.csv')
except FileNotFoundError:
    df = pd.read_csv('/results.csv')

df = df.dropna(subset=['HomeTeam', 'AwayTeam', 'FTR']).copy()
df['HomeWin'] = (df['FTR'] == 'H').astype(int)

home_wr = df.groupby('HomeTeam')['HomeWin'].mean().reset_index().rename(columns={'HomeWin': 'HomeTeam_HomeWinRate'})
away_lr = df.groupby('AwayTeam')['HomeWin'].mean().reset_index().rename(columns={'HomeWin': 'AwayTeam_AwayLossRate'})

df = df.merge(home_wr, on='HomeTeam', how='left')
df = df.merge(away_lr, on='AwayTeam', how='left')

features = ['HomeTeam_HomeWinRate', 'AwayTeam_AwayLossRate']
X = df[features]
y = df['HomeWin']

kf = KFold(n_splits=5, shuffle=True, random_state=42)
clf = LogisticRegression(random_state=42)
y_proba = cross_val_predict(clf, X, y, cv=kf, method='predict_proba')[:, 1]

thresholds = np.arange(0.1, 1.0, 0.1)
threshold_metrics = []

for t in thresholds:
    y_pred_t = (y_proba >= t).astype(int)
    threshold_metrics.append({
        'Threshold': round(t, 1),
        'Precision': precision_score(y, y_pred_t, zero_division=0),
        'Recall': recall_score(y, y_pred_t, zero_division=0),
        'F1-Score': f1_score(y, y_pred_t, zero_division=0),
        'MCC': matthews_corrcoef(y, y_pred_t)
    })

thresh_df = pd.DataFrame(threshold_metrics)
print("--- Threshold Sensitivity Performance Table ---")
display(thresh_df.round(4))

sns.set_theme(style='whitegrid')
fig, axes = plt.subplots(1, 3, figsize=(18, 5))

axes[0].plot(thresh_df['Threshold'], thresh_df['Precision'], marker='o', label='Precision', lw=2)
axes[0].plot(thresh_df['Threshold'], thresh_df['Recall'], marker='s', label='Recall', lw=2)
axes[0].plot(thresh_df['Threshold'], thresh_df['F1-Score'], marker='^', label='F1-Score', lw=2)
axes[0].plot(thresh_df['Threshold'], thresh_df['MCC'], marker='d', label='MCC', lw=2)
axes[0].set_title('Metrics vs. Decision Threshold', fontsize=12, fontweight='bold')
axes[0].set_xlabel('Decision Threshold', fontsize=10)
axes[0].set_ylabel('Score', fontsize=10)
axes[0].legend()

betas = np.linspace(0.1, 3.0, 50)
for t_val in [0.3, 0.4, 0.5, 0.6, 0.7]:
    preds = (y_proba >= t_val).astype(int)
    f_betas = [fbeta_score(y, preds, beta=b, zero_division=0) for b in betas]
    axes[1].plot(betas, f_betas, label=f'Threshold = {t_val}', lw=2)
axes[1].set_title(r'$F_\beta$-Score vs. $\beta$', fontsize=12, fontweight='bold')
axes[1].set_xlabel(r'$\beta$ (Recall Weight)', fontsize=10)
axes[1].set_ylabel(r'$F_\beta$ Score', fontsize=10)
axes[1].legend()

fpr, tpr, _ = roc_curve(y, y_proba)
auc_score = roc_auc_score(y, y_proba)
axes[2].plot(fpr, tpr, color='darkorange', lw=2.5, label=f'ROC Curve (AUC = {auc_score:.3f})')
axes[2].plot([0, 1], [0, 1], color='navy', lw=1.5, linestyle='--', label='Random Guess')
axes[2].set_title('Receiver Operating Characteristic (ROC)', fontsize=12, fontweight='bold')
axes[2].set_xlabel('False Positive Rate (FPR)', fontsize=10)
axes[2].set_ylabel('True Positive Rate (TPR)', fontsize=10)
axes[2].legend(loc='lower right')

plt.tight_layout()
plt.show()



